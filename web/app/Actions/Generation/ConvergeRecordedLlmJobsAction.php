<?php

namespace App\Actions\Generation;

use App\Enums\GenerationJobStatus;
use App\Enums\TestCaseSource;
use App\Enums\TestCaseStatus;
use App\Models\GenerationJob;
use App\Models\TestCase;
use App\Models\TestSuite;
use App\Services\Dsl\DslValidator;
use Illuminate\Support\Facades\DB;

/**
 * Brings replayed LLM/HYBRID jobs imported by an earlier `ait:demo:showcase` up to the messages a
 * replay gets today (QA S14-06 round 3): ImportRecordedLlmJobAction only rewords the recorded
 * ai-service errors of a new import, so jobs imported before kept English opis text ("The properties
 * must match schema: steps") and one problem worded twice (web "Tham số query ..." next to
 * ai-service "Tham số truy vấn ...").
 *
 * Only jobs marked as a replay (params.recorded_source_job_id) are touched, and in them only the
 * INVALID cases still generated by the LLM (a case a visitor edited is MANUAL and kept as is). Each
 * such case gets the errors the import computes now (ProcessGeneratedTestCasesAction::invalidCaseErrors:
 * the web validation errors of its DSL, else the reworded recorded errors). The job keeps its status
 * and counts; stats are reduced to the five M11 counters and a finished replay carries no error,
 * as an import stores them. llm_call_logs are insert-only (§5) and never touched. Idempotent: a
 * second call changes nothing.
 */
class ConvergeRecordedLlmJobsAction
{
    private const STATS_KEYS = ['generated', 'valid', 'invalid', 'duplicates', 'repaired'];

    public function __construct(
        private readonly DslValidator $validator,
    ) {}

    /**
     * @return array{jobs: int, cases: int} Number of job and test case rows changed.
     */
    public function execute(TestSuite $suite): array
    {
        $changedJobs = 0;
        $changedCases = 0;

        $jobs = GenerationJob::query()
            ->where('test_suite_id', $suite->id)
            ->with('apiSpec')
            ->orderBy('id')
            ->get()
            ->filter(static fn (GenerationJob $job): bool => $job->isReplayed());

        foreach ($jobs as $job) {
            DB::transaction(function () use ($job, &$changedJobs, &$changedCases): void {
                $changedCases += $this->convergeCases($job);
                $changedJobs += $this->convergeJob($job) ? 1 : 0;
            });
        }

        return ['jobs' => $changedJobs, 'cases' => $changedCases];
    }

    private function convergeCases(GenerationJob $job): int
    {
        $changed = 0;
        $cases = TestCase::query()
            ->where('generation_job_id', $job->id)
            ->where('status', TestCaseStatus::Invalid->value)
            ->whereIn('source', [TestCaseSource::Llm->value, TestCaseSource::Hybrid->value])
            ->orderBy('id')
            ->get();

        foreach ($cases as $case) {
            $rawDsl = $case->getRawOriginal('dsl');
            $webErrors = $this->validator
                ->validate(is_string($rawDsl) ? $rawDsl : $case->dsl, $job->apiSpec, $job->contextVariables())
                ->errors;
            $errors = ProcessGeneratedTestCasesAction::invalidCaseErrors(
                $webErrors,
                ImportRecordedLlmJobAction::currentMessages($case->validation_errors ?? []),
            );

            /** @var mixed $stored */
            $stored = $case->getAttribute('validation_errors');
            if ($errors !== $stored) {
                $case->forceFill(['validation_errors' => $errors])->save();
                $changed++;
            }
        }

        return $changed;
    }

    private function convergeJob(GenerationJob $job): bool
    {
        $attributes = [];

        $stats = is_array($job->stats) ? $job->stats : [];
        $current = [];
        foreach (self::STATS_KEYS as $key) {
            $current[$key] = isset($stats[$key]) && is_numeric($stats[$key])
                ? (int) $stats[$key]
                : $this->countFor($job, $key);
        }
        // jsonb does not keep key order: compare the counters, not their order.
        $sortedStats = $stats;
        ksort($sortedStats);
        $sortedCurrent = $current;
        ksort($sortedCurrent);
        if ($sortedCurrent !== $sortedStats) {
            $attributes['stats'] = $current;
        }

        // A finished replay (SUCCEEDED/PARTIAL) is stored without an error by the import.
        $finished = in_array($job->status, [GenerationJobStatus::Succeeded, GenerationJobStatus::Partial], true);
        if ($finished && $job->error !== null) {
            $attributes['error'] = null;
        }

        if ($attributes === []) {
            return false;
        }

        $job->forceFill($attributes)->save();

        return true;
    }

    /** A counter missing from the stored stats, counted from the job's cases. */
    private function countFor(GenerationJob $job, string $key): int
    {
        $query = TestCase::query()->where('generation_job_id', $job->id);

        return match ($key) {
            'valid' => $query->whereIn('status', [TestCaseStatus::Valid->value, TestCaseStatus::Approved->value, TestCaseStatus::Archived->value])->count(),
            'invalid' => $query->where('status', TestCaseStatus::Invalid->value)->count(),
            'duplicates' => $query->where('status', TestCaseStatus::Duplicate->value)->count(),
            'repaired' => $query->where('repair_attempts', '>', 0)->where('status', '!=', TestCaseStatus::Invalid->value)->count(),
            default => $query->count(),
        };
    }
}
